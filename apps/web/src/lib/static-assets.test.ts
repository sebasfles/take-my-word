import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { staticAssets } from "./static-assets.ts";

const web = join(import.meta.dirname, "..", "..");
const brand = join(web, "..", "..", "packages", "brand", "src", "assets");
const published = join(web, "public", "static");

describe("public/static", () => {
  it("holds exactly the brand assets with fixed URLs", () => {
    expect(readdirSync(published).sort()).toEqual([...staticAssets].sort());
  });

  it.each(staticAssets)("serves %s as generated by the brand package", (file) => {
    expect(readFileSync(join(published, file)).equals(readFileSync(join(brand, file)))).toBe(true);
  });
});
