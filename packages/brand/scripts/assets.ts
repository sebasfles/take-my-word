const light = tokens.light.colors;
const dark = tokens.dark.colors;
const round = (d: string) =>
  d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 100) / 100));

interface Box {
  minX: number;
  minY: number;
  maxX: number;
  maxY: number;
}

function text(font: fontkit.Font, value: string, size: number, x: number, baseline: number) {
  const scale = size / font.unitsPerEm;
  const run = font.layout(value);
  let cursor = x;
  const parts: string[] = [];
  const box: Box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
  run.glyphs.forEach((g, index) => {
    const path = g.path.scale(scale, -scale).translate(cursor, baseline);
    const b = path.bbox;
    if (Number.isFinite(b.minX)) {
      box.minX = Math.min(box.minX, b.minX);
      box.minY = Math.min(box.minY, b.minY);
      box.maxX = Math.max(box.maxX, b.maxX);
      box.maxY = Math.max(box.maxY, b.maxY);
    }
    parts.push(path.toSVG());
    cursor += (run.positions[index]?.xAdvance ?? 0) * scale;
  });
  return { d: round(parts.join("")), end: cursor, box };
}

const roman = await staticInstance(faces.fraunces, { wght: 600, opsz: 36 });
const italic = await staticInstance(faces.frauncesItalic, { wght: 520, opsz: 36 });
const display = await staticInstance(faces.fraunces, { wght: 560 });
const displayItalic = await staticInstance(faces.frauncesItalic, { wght: 440 });
const sans = await staticInstance(faces.instrumentSans, { wght: 500 });

const size = 100;
const baseline = 100;
const capHeight = (roman.capHeight / roman.unitsPerEm) * size;
const markSize = capHeight * 1.5;
const markScale = markSize / 64;
const markTop = baseline - capHeight / 2 - markSize / 2 - 4;
const textX = markSize + size * 0.22;
const takeMy = text(roman, "Take My", size, textX, baseline);
const word = text(italic, "Word", size, takeMy.end + size * 0.2, baseline);
const top = Math.min(markTop, takeMy.box.minY, word.box.minY) - 2;
const bottom = Math.max(takeMy.box.maxY, word.box.maxY) + 2;
const width = Math.ceil(word.box.maxX + 2);
const height = Math.ceil(bottom - top);
const minY = Math.floor(top);
const viewBox = `0 ${String(minY)} ${String(width)} ${String(height)}`;
const wordmark = {
  viewBox,
  width,
  height,
  mark: `translate(0 ${markTop.toFixed(2)}) scale(${markScale.toFixed(4)})`,
  roman: takeMy.d,
  italic: word.d,
};

writeFileSync(
  join(src, "wordmark-paths.ts"),
  [
    "// Generated by packages/brand/scripts/assets.ts. Do not edit.",
    `export const wordmark = ${JSON.stringify(wordmark, null, 2)};`,
    "",
  ].join("\n"),
);

function wordmarkSvg(colors: typeof light) {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${String(width)}" height="${String(height)}">`,
    `<path d="${glyph}" transform="${wordmark.mark}" fill="${colors.accent}"/>`,
    `<path d="${wordmark.roman}" fill="${colors.text}"/>`,
    `<path d="${wordmark.italic}" fill="${colors.accentText}"/>`,
    "</svg>",
  ].join("\n");
}

const markSvg = (fill: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><path d="${glyph}" fill="${fill}"/></svg>\n`;

function iconSvg(small: boolean, { rounded = true, inset = 0 } = {}) {
  const radius = rounded ? tile.radius : 0;
  const scale = 1 - inset * 2;
  const glyphPath = small
    ? `<path d="${glyphSmall}" fill="${light.onAccent}"/>`
    : `<path d="${glyph}" transform="${glyphInTile}" fill="${light.onAccent}"/>`;
  const inner =
    inset === 0
      ? glyphPath
      : `<g transform="translate(${String(32 - 32 * scale)} ${String(32 - 32 * scale)}) scale(${String(scale)})">${glyphPath}</g>`;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">`,
    `<rect width="64" height="64" rx="${String(radius)}" fill="${light.accent}"/>`,
    inner,
    "</svg>",
    "",
  ].join("\n");
}

const png = (svg: string, px: number) =>
  new Resvg(svg, { fitTo: { mode: "width", value: px } }).render().asPng();

const iconFor = (px: number) => png(iconSvg(px <= 48), px);

function ogSvg() {
  const w = 1200;
  const h = 630;
  const pad = 88;
  const logoHeight = 64;
  const logoScale = logoHeight / height;
  const line1 = text(display, "Say it once.", 128, pad, 330);
  const line2 = text(displayItalic, "It’s written.", 128, pad, 470);
  const tagline = text(sans, "Your Word, Our Command.", 34, pad, 560);
  const url = text(sans, "takemyword.fless.dev", 26, 0, 0);
  const urlWidth = url.end;
  const urlLine = text(sans, "takemyword.fless.dev", 26, w - pad - urlWidth, 560);
  const bars = [0.42, 0.7, 1, 0.78, 0.5, 0.86, 0.34];
  const barWidth = 20;
  const gap = 16;
  const barsX = w - pad - bars.length * barWidth - (bars.length - 1) * gap;
  if (Math.max(line1.box.maxX, line2.box.maxX) > barsX - 48) {
    throw new Error("the OG headline runs into the waveform");
  }
  const barRects = bars
    .map((weight, index) => {
      const bh = 300 * weight;
      return `<rect x="${String(barsX + index * (barWidth + gap))}" y="${String(330 - bh / 2)}" width="${String(barWidth)}" height="${bh.toFixed(1)}" rx="${String(barWidth / 2)}" fill="${light.accent}" opacity="${(0.35 + weight * 0.65).toFixed(2)}"/>`;
    })
    .join("");
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${String(w)} ${String(h)}" width="${String(w)}" height="${String(h)}">`,
    `<rect width="${String(w)}" height="${String(h)}" fill="${light.bg}"/>`,
    `<g transform="translate(${String(pad)} 72) scale(${logoScale.toFixed(4)}) translate(0 ${String(-minY)})">${wordmarkSvg(light).split("\n").slice(1, -1).join("")}</g>`,
    barRects,
    `<path d="${line1.d}" fill="${light.text}"/>`,
    `<path d="${line2.d}" fill="${light.accentText}"/>`,
    `<path d="${tagline.d}" fill="${light.muted}"/>`,
    `<path d="${urlLine.d}" fill="${light.muted}"/>`,
    "</svg>",
  ].join("\n");
}

