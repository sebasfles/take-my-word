import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { faces, staticInstance, webSubset, type Face } from "./font-sources.ts";

const out = join(import.meta.dirname, "..", "src");
const sample =
  "Mantén Ctrl y Win, habla y suelta: el texto limpio aparece en la app que tienes delante.";

const fallbacks = {
  serif: { names: ["Times New Roman", "Liberation Serif", "Tinos"], sampleWidth: 34.7656 },
  sans: { names: ["Arial", "Liberation Sans", "Arimo"], sampleWidth: 38.3555 },
};

const percent = (value: number) => `${(value * 100).toFixed(2)}%`;

async function fallbackFace(face: Face): Promise<string> {
  const instance = await staticInstance(face, face.metricsAt);
  const width =
    instance.layout(sample).positions.reduce((sum, position) => sum + position.xAdvance, 0) /
    instance.unitsPerEm;
  const fallback = fallbacks[face.fallback];
  const sizeAdjust = width / fallback.sampleWidth;
  const em = instance.unitsPerEm * sizeAdjust;
  return [
    "@font-face {",
    `  font-family: "${face.family} Fallback";`,
    `  font-style: ${face.style};`,
    `  src: ${fallback.names.map((name) => `local("${name}")`).join(", ")};`,
    `  size-adjust: ${percent(sizeAdjust)};`,
    `  ascent-override: ${percent(instance.ascent / em)};`,
    `  descent-override: ${percent(Math.abs(instance.descent) / em)};`,
    `  line-gap-override: ${percent(instance.lineGap / em)};`,
    "}",
  ].join("\n");
}

const blocks: string[] = [];
for (const face of Object.values(faces)) {
  const subset = await webSubset(face);
  writeFileSync(join(out, "fonts", face.file), subset);
  blocks.push(
    [
      "@font-face {",
      `  font-family: "${face.family}";`,
      `  font-style: ${face.style};`,
      `  font-weight: ${String(face.weight[0])} ${String(face.weight[1])};`,
      "  font-display: swap;",
      `  src: url("./fonts/${face.file}") format("woff2");`,
      "}",
    ].join("\n"),
    await fallbackFace(face),
  );
  process.stdout.write(`${face.file}: ${String(subset.length)} bytes\n`);
}

writeFileSync(
  join(out, "fonts.css"),
  [
    "/* Generated by packages/brand/scripts/fonts.ts. Do not edit. */",
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n"),
);
